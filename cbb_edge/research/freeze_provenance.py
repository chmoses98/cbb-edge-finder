"""Automated, fail-closed freeze provenance for prospective projection manifests (RESEARCH ONLY).

Question answered per manifest on ``projections-archive``: by what SERVER-SIDE time was this manifest,
and every frozen record it hashes, on ``origin``? The answer is derived deterministically from two
inputs, never typed by hand:

1. the archive's git history (local checkout): the single commit that ADDED the manifest, absent from
   its parent, an ancestor of the evaluated head, with the manifest and every record it lists byte-
   identical at that commit and at the head, and every head record matching its manifest sha256;
2. saved GitHub Actions job records (``provenance_evidence.json``): GitHub's own step timestamps.

A manifest is VERIFIED only when exactly one ``prospective-projections`` job satisfies: job and the
"Append to projections-archive" step concluded ``success``; the job's ``head_sha`` equals the
manifest's embedded ``code_sha``; the manifest ``as_of`` precedes the step start; and the archive
commit's committer time falls inside the step window (+/- ``TOLERANCE_S``, second-truncated server
times). ``pushed_by`` = that step's ``completed_at`` (server clock): the push happens inside the step,
so this is an upper bound on the push time. Anything else (no candidate, several candidates, missing
git object, a changed byte) leaves the manifest UNVERIFIED and its records are not gradable.
"""

from __future__ import annotations

import hashlib
import json
import subprocess
import time
import urllib.error
import urllib.request
from collections.abc import Callable, Iterable
from datetime import UTC, datetime, timedelta
from pathlib import Path
from typing import Any

WORKFLOW = "prospective-projections"
APPEND_STEP = "Append to projections-archive (never overwrite)"
TOLERANCE_S = 2
MANIFEST_DIR = "projections/manifests"
NOTE = (
    "GENERATED by cbb_edge.research.freeze_provenance from the projections-archive git history and "
    "the GitHub Actions job records in provenance_evidence.json; do not edit by hand. pushed_by = "
    "server-side completed_at of the 'Append to projections-archive (never overwrite)' step of the "
    "unique job whose head_sha equals the manifest code_sha and whose step window contains the "
    "archive commit. Manifests under _unverified (or absent) are NOT provably frozen."
)


def _ts(s: Any) -> datetime | None:
    if not s:
        return None
    try:
        t = datetime.fromisoformat(str(s).replace("Z", "+00:00"))
    except ValueError:
        return None
    return t if t.tzinfo is not None else None


def _git(root: Path, *args: str) -> str | None:
    p = subprocess.run(["git", "-C", str(root), *args], capture_output=True, text=True, check=False)
    return p.stdout.strip() if p.returncode == 0 else None


def _blob(root: Path, rev: str, path: str) -> str | None:
    return _git(root, "rev-parse", "--verify", "-q", f"{rev}:{path}")


def trim_job(job: dict[str, Any]) -> dict[str, Any]:
    """Keep only the fields the verifier reads from a GitHub Actions job object."""
    step = next((s for s in job.get("steps") or [] if s.get("name") == APPEND_STEP), None)
    return {
        "job_id": job.get("id"),
        "run_id": job.get("run_id"),
        "run_attempt": job.get("run_attempt"),
        "workflow_name": job.get("workflow_name"),
        "head_sha": job.get("head_sha"),
        "conclusion": job.get("conclusion"),
        "append_step": None
        if step is None
        else {k: step.get(k) for k in ("conclusion", "started_at", "completed_at")},
    }


def adding_commits(root: Path, rel: str) -> list[dict[str, str]]:
    """Every commit (reachable from HEAD) that added ``rel``; normally exactly one."""
    out = _git(root, "log", "--diff-filter=A", "--format=%H %P %cI", "HEAD", "--", rel)
    if out is None:
        return []
    rows = []
    for line in out.splitlines():
        parts = line.split()
        if len(parts) >= 3:
            rows.append({"commit": parts[0], "parents": parts[1:-1], "committer_date": parts[-1]})
    return rows


def verify_manifest(
    root: Path, stem: str, jobs: Iterable[dict[str, Any]], *, tolerance_s: int = TOLERANCE_S
) -> dict[str, Any]:
    """Provenance of one manifest: ``{"verified": True, "pushed_by": ...}`` or a fail-closed reason."""
    rel = f"{MANIFEST_DIR}/{stem}.json"
    fail: dict[str, Any] = {"verified": False}
    path = root / rel
    if not path.exists():
        return {**fail, "reason": "manifest_missing_at_head"}
    try:
        m = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {**fail, "reason": "manifest_unreadable"}
    as_of, code_sha = _ts(m.get("as_of")), m.get("code_sha")
    if as_of is None or not code_sha or not isinstance(m.get("files"), dict):
        return {**fail, "reason": "manifest_fields_invalid"}
    adds = adding_commits(root, rel)
    if len(adds) != 1:
        return {**fail, "reason": f"manifest_added_by_{len(adds)}_commits"}
    c = adds[0]
    if len(c["parents"]) != 1 or _blob(root, c["parents"][0], rel) is not None:
        return {**fail, "reason": "parent_not_unique_or_already_had_manifest", "archive_commit": c["commit"]}  # fmt: skip
    blob = _blob(root, c["commit"], rel)
    if blob is None or blob != _blob(root, "HEAD", rel):
        return {**fail, "reason": "manifest_changed_after_commit", "archive_commit": c["commit"]}
    for f, h in m["files"].items():
        fp = f"projections/{f}"
        b = _blob(root, c["commit"], fp)
        if b is None or b != _blob(root, "HEAD", fp):
            return {**fail, "reason": "record_absent_or_changed_after_commit", "record": f}
        if not (root / fp).exists() or hashlib.sha256((root / fp).read_bytes()).hexdigest() != h:
            return {**fail, "reason": "record_hash_mismatch_at_head", "record": f}
    committed = _ts(c["committer_date"])
    if committed is None:
        return {**fail, "reason": "committer_date_unparseable"}
    tol = timedelta(seconds=tolerance_s)
    cands = []
    for j in jobs:
        s = j.get("append_step") or {}
        st, ct = _ts(s.get("started_at")), _ts(s.get("completed_at"))
        if (
            j.get("workflow_name") == WORKFLOW
            and j.get("conclusion") == "success"
            and s.get("conclusion") == "success"
            and j.get("head_sha") == code_sha
            and st is not None
            and ct is not None
            and as_of < st
            and st - tol <= committed <= ct + tol
        ):
            cands.append((j, ct))
    if len(cands) != 1:
        return {**fail, "reason": f"{len(cands)}_matching_actions_jobs", "archive_commit": c["commit"]}  # fmt: skip
    j, ct = cands[0]
    return {
        "verified": True,
        "manifest_as_of": m["as_of"],
        "code_sha": code_sha,
        "archive_commit": c["commit"],
        "archive_commit_parent": c["parents"][0],
        "committer_date": c["committer_date"],
        "manifest_blob": blob,
        "n_records": len(m["files"]),
        "actions_run": j.get("run_id"),
        "actions_job": j.get("job_id"),
        "append_step_started_at": j["append_step"]["started_at"],
        "append_step_completed_at": j["append_step"]["completed_at"],
        "pushed_by": ct.isoformat(),
    }


def manifests_from(root: Path, since: datetime) -> list[str]:
    """Stems of manifests whose ``as_of`` >= ``since`` (only these can hold eligible records)."""
    out = []
    for p in sorted((root / MANIFEST_DIR).glob("*.json")):
        try:
            a = _ts(json.loads(p.read_text(encoding="utf-8")).get("as_of"))
        except (OSError, ValueError):
            a = None
        if a is None or a >= since:  # unparseable: include so it is reported as unverified
            out.append(p.stem)
    return out


def build(root: Path, evidence: dict[str, Any], since: datetime) -> dict[str, Any]:
    """``freeze_provenance.json`` content: verified manifests at top level, failures under
    ``_unverified``. ``wave14.freeze_pushed_at`` only reads top-level ``pushed_by``."""
    jobs = evidence.get("jobs") or []
    out: dict[str, Any] = {"_note": NOTE, "_evidence_fetched_at": evidence.get("fetched_at")}
    bad: dict[str, Any] = {}
    git_ok = _git(root, "rev-parse", "HEAD")
    for stem in manifests_from(root, since):
        r = verify_manifest(root, stem, jobs) if git_ok else {"verified": False, "reason": "projections_root_not_a_git_checkout"}  # fmt: skip
        if r.pop("verified"):
            out[stem] = r
        else:
            bad[stem] = r
    out["_archive_head"] = git_ok
    out["_unverified"] = bad
    return out


def _http_get_json(token: str) -> Callable[[str], Any]:  # pragma: no cover - network
    def get(url: str) -> Any:
        req = urllib.request.Request(url, headers={"Authorization": f"Bearer {token}", "Accept": "application/vnd.github+json", "X-GitHub-Api-Version": "2022-11-28"})  # fmt: skip
        for attempt in range(4):
            try:
                with urllib.request.urlopen(req, timeout=30) as r:
                    return json.load(r)
            except (urllib.error.URLError, TimeoutError):
                if attempt == 3:
                    raise
                time.sleep(2**attempt)
        return None

    return get


def fetch_evidence(
    repo: str,
    created_from: str,
    *,
    known_run_ids: Iterable[int] = (),
    token: str | None = None,
    get: Callable[[str], Any] | None = None,
) -> dict[str, Any]:
    """Pull completed ``prospective-projections`` job records from the GitHub REST API (read-only;
    the token needs ``actions: read``). Incremental: runs already in the evidence are not re-read, so
    each run costs one jobs request once. Records are GitHub's own; nothing is synthesised."""
    if get is None:
        if not token:
            raise ValueError("fetch_evidence needs a token (actions: read) or a get callable")
        get = _http_get_json(token)
    known = set(known_run_ids)
    base = f"https://api.github.com/repos/{repo}/actions"
    jobs: list[dict[str, Any]] = []
    listed = read = 0
    page = 1
    while True:
        d = get(f"{base}/workflows/{WORKFLOW}.yml/runs?status=completed&per_page=100&page={page}&created=%3E%3D{created_from}")  # fmt: skip
        runs = d.get("workflow_runs") or []
        for run in runs:
            listed += 1
            if run.get("id") in known:
                continue
            read += 1
            for j in get(f"{base}/runs/{run['id']}/jobs?filter=all&per_page=100").get("jobs") or []:
                jobs.append(trim_job(j))
        if len(runs) < 100:
            break
        page += 1
    return {"source": "GitHub REST API", "fetched_at": datetime.now(UTC).isoformat(timespec="seconds"),
            "runs_listed": listed, "runs_read": read, "jobs": jobs}  # fmt: skip


def merge_evidence(old: dict[str, Any], new_jobs: Iterable[dict[str, Any]]) -> list[dict[str, Any]]:
    """Union of job records keyed by job id (a later record of the same job replaces the earlier)."""
    by = {j["job_id"]: j for j in old.get("jobs") or []}
    for j in new_jobs:
        by[j["job_id"]] = j
    return [by[k] for k in sorted(by)]
