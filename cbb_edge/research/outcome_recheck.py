"""Re-observe graded finals from the free ESPN scoreboard (RESEARCH_ONLY, read-only).

The schedule archive records finals as they are captured. This module re-reads the public
scoreboard *later* for every graded game and records what ESPN reports now, so a final that was
captured early, mis-scored or later corrected shows up as a MISMATCH instead of silently grading.

Same provider as the archive (not an independent organisation): it confirms finality and the
absence of later corrections, not the score itself from a second source.

Scores are stored in ESPN's home/away frame. ``compare`` maps them into the projection frame
using the archived orientation (SAME / SWAPPED) before comparing with the graded final.
"""

from __future__ import annotations

from collections import Counter
from collections.abc import Callable, Iterable
from datetime import UTC, datetime
from typing import Any

SITE = "https://site.api.espn.com/apis/site/v2/sports/basketball/mens-college-basketball"
NOTE = (
    "GENERATED by cbb_edge.research.outcome_recheck from the free public ESPN scoreboard "
    "(site.api.espn.com, groups=50), re-read after the schedule archive's capture. Same provider "
    "as the archive (not a different organisation): it confirms the archived finals are final and "
    "were not later corrected. Scores are in ESPN's home/away frame; the comparison applies the "
    "archived orientation. Entries are keyed by game_id; the latest re-observation is kept and "
    "earlier differing observations are preserved under 'history'."
)


def parse_scoreboard(payload: dict[str, Any]) -> dict[int, dict[str, Any]]:
    """``{game_id: {espn_status, espn_home_id, espn_away_id, home, away}}`` from a scoreboard."""
    out: dict[int, dict[str, Any]] = {}
    for ev in payload.get("events") or []:
        comp = (ev.get("competitions") or [{}])[0]
        sides = {c.get("homeAway"): c for c in comp.get("competitors") or []}
        h, a = sides.get("home"), sides.get("away")
        if h is None or a is None or not str(ev.get("id", "")).isdigit():
            continue
        status = ((comp.get("status") or ev.get("status") or {}).get("type") or {}).get("name")
        try:
            hs, as_ = int(h.get("score")), int(a.get("score"))
        except (TypeError, ValueError):
            hs = as_ = None  # type: ignore[assignment]
        out[int(ev["id"])] = {
            "espn_status": status,
            "espn_home_id": str((h.get("team") or {}).get("id")),
            "espn_away_id": str((a.get("team") or {}).get("id")),
            "home": hs,
            "away": as_,
        }
    return out


def recheck(
    graded: Iterable[dict[str, Any]],
    fetch_day: Callable[[str], dict[str, Any]],
    existing: dict[str, Any] | None = None,
    *,
    now: datetime | None = None,
) -> dict[str, Any]:
    """Re-observe every graded game (``{"game_id", "date" (ET, YYYY-MM-DD)}``) and merge.

    ``fetch_day("YYYYMMDD")`` returns the scoreboard payload for one ET date. Games ESPN no longer
    lists are recorded with ``espn_status = "NOT_LISTED"`` (never dropped).
    """
    when = (now or datetime.now(UTC)).isoformat(timespec="seconds")
    games = {int(g["game_id"]): g for g in (existing or {}).get("games") or []}
    by_date: dict[str, list[int]] = {}
    for g in graded:
        by_date.setdefault(str(g["date"]), []).append(int(g["game_id"]))
    for day, ids in sorted(by_date.items()):
        seen = parse_scoreboard(fetch_day(day.replace("-", "")))
        for gid in ids:
            obs = seen.get(gid) or {"espn_status": "NOT_LISTED", "home": None, "away": None}
            new = {"game_id": gid, **obs, "observed_at": when}
            old = games.get(gid)
            if old is not None:
                hist = list(old.get("history") or [])
                if (old.get("home"), old.get("away"), old.get("espn_status")) != (
                    new["home"],
                    new["away"],
                    new["espn_status"],
                ):
                    hist.append({k: v for k, v in old.items() if k != "history"})
                if hist:
                    new["history"] = hist
            games[gid] = new
    return {"_note": NOTE, "fetched_at": when, "games": [games[k] for k in sorted(games)]}


def compare(crosscheck: dict[str, Any], rows: Iterable[dict[str, Any]]) -> dict[str, Any]:
    """Count graded rows whose re-observed final matches (margin, total) in the projection frame.

    Each row needs ``game_id``, ``actual_margin``, ``actual_total`` and ``orientation``.
    """
    got = {int(g["game_id"]): g for g in crosscheck.get("games") or []}
    by: Counter[str] = Counter()
    bad: list[int] = []
    for r in rows:
        g = got.get(int(r["game_id"]))
        if g is None:
            by["not_rechecked"] += 1
            continue
        if g.get("espn_status") != "STATUS_FINAL" or g.get("home") is None:
            by["NOT_FINAL_ON_RECHECK"] += 1
            bad.append(int(r["game_id"]))
            continue
        sign = -1 if r.get("orientation") == "SWAPPED" else 1
        obs = (sign * (g["home"] - g["away"]), g["home"] + g["away"])
        if obs == (r["actual_margin"], r["actual_total"]):
            by["match"] += 1
        else:
            by["MISMATCH"] += 1
            bad.append(int(r["game_id"]))
    return {"graded_finals": dict(by), "problem_game_ids": sorted(bad)}
